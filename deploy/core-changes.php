<?php

/*
 * Writes docs/core-changes.md: every LaraClassifier file changed, deleted or added since the
 * first commit (the stock script). Run it before upgrading LaraClassifier, then re-apply or
 * re-check each changed file after the upgrade.
 *
 *   php deploy/core-changes.php
 */

$root = dirname(__DIR__);
chdir($root);

$base = trim((string)shell_exec('git rev-list --max-parents=0 HEAD | tail -n 1'));
if ($base === '') {
	fwrite(STDERR, "Not a git repository, or no commits.\n");
	exit(1);
}

$lines = array_filter(explode("\n", (string)shell_exec('git diff --name-status --no-renames ' . escapeshellarg($base) . ' HEAD')));

/** Generated or data files that are not code to re-apply. */
$ignored = '#^(public/dist/|public/mix-manifest\.json|composer\.lock|package-lock\.json|storage/|tests/)#';

$groups = ['M' => [], 'D' => [], 'A' => []];
foreach ($lines as $line) {
	[$status, $path] = array_pad(preg_split('/\s+/', $line, 2), 2, '');
	if ($path === '' || preg_match($ignored, $path) || !isset($groups[$status])) {
		continue;
	}
	$groups[$status][] = $path;
}

$isMarked = function (string $path): bool {
	return is_file($path) && preg_match('/adniro|custom:|CUSTOM-/i', (string)file_get_contents($path)) === 1;
};

$section = function (string $title, string $intro, array $paths, bool $showMarks) use ($isMarked): string {
	sort($paths);
	$byFolder = [];
	foreach ($paths as $path) {
		$folder = implode('/', array_slice(explode('/', $path), 0, 2));
		$byFolder[$folder][] = $path;
	}
	ksort($byFolder);

	$out = "## {$title} (" . count($paths) . ")\n\n{$intro}\n\n";
	foreach ($byFolder as $folder => $files) {
		$out .= "### {$folder}\n\n";
		foreach ($files as $file) {
			$mark = ($showMarks && !$isMarked($file)) ? ' (no marker comment)' : '';
			$out .= "- `{$file}`{$mark}\n";
		}
		$out .= "\n";
	}

	return $out;
};

$doc = "# Changes to LaraClassifier core files\n\n"
	. "Generated by `php deploy/core-changes.php` on " . date('Y-m-d') . ", against the first commit (`" . substr($base, 0, 8) . "`), which holds the stock script.\n"
	. "Built files (`public/dist`, `mix-manifest.json`), lock files and tests are left out.\n\n"
	. "**Before upgrading LaraClassifier:** run the script again, upgrade on a branch, then check every file in \"Changed\" and \"Deleted\" with `git diff " . substr($base, 0, 8) . " -- <file>`. Changes from the AI and professional-site work carry an `adniro` comment; earlier changes (marked \"no marker comment\") usually don't, so compare those carefully. Files in \"Added\" are ours and normally survive an upgrade.\n\n"
	. $section('Changed', 'Stock files we edited.', $groups['M'], true)
	. $section('Deleted', 'Stock files removed from this site. An upgrade may bring them back.', $groups['D'], false)
	. $section('Added', 'Files that are not part of LaraClassifier.', $groups['A'], false);

file_put_contents($root . '/docs/core-changes.md', $doc);

printf("docs/core-changes.md: %d changed, %d deleted, %d added\n", count($groups['M']), count($groups['D']), count($groups['A']));
